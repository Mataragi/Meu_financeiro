def _psql(container, sql, check=True):
    resultado = subprocess.run(
        [
            "docker", "exec", "-i", container, "psql", "-X",
            "-v", "ON_ERROR_STOP=1", "-U", "postgres",
            "-d", "financeiro_pro_test", "-A", "-t",
        ],
        input=sql,
        capture_output=True,
        text=True,
        check=False,
    )
    if check and resultado.returncode != 0:
        raise AssertionError(resultado.stderr or resultado.stdout)
    return resultado


def _semear(container, valores):
    _psql(container, "TRUNCATE public.transacoes RESTART IDENTITY CASCADE;")
    if valores:
        linhas = []
        for item in valores:
            identificador, status, data_liquidacao, valor, mes, ano = item
            data_sql = "NULL" if data_liquidacao is None else f"'{data_liquidacao}'"
            valor_sql = "NULL" if valor is None else str(valor)
            linhas.append(
                f"({identificador}, '{status}', {data_sql}, {valor_sql}, '{mes}', {ano}, "
                f"'Registro {identificador}', 'Outros', 'PIX', 10, '2026-10-01')"
            )
        _psql(
            container,
            "INSERT INTO public.transacoes "
            "(id, status, data_liquidacao, valor, mes, ano, descricao, categoria, "
            "forma_pagamento, vencimento, data_transacao) VALUES "
            + ",".join(linhas)
            + ";",
        )


def _chamar_funcao(ids, data="2026-11-14", atualizacoes="{}"):
    ids_sql = ",".join(str(item) for item in ids)
    return (
        "SET ROLE service_role; "
        f"SELECT pg_catalog.count(*) FROM public.liquidar_transacoes("
        f"ARRAY[{ids_sql}]::bigint[], '{data}'::date, '{atualizacoes}'::jsonb); "
        "RESET ROLE;"
    )


def test_postgres_liquida_lote_preservando_competencia_e_campos_permitidos(postgres_container):
    _semear(postgres_container, [
        (1, "Pendente", None, 100.0, "OUTUBRO", 2026),
        (2, "Pendente", None, 150.0, "NOVEMBRO", 2026),
    ])

    resultado = _psql(
        postgres_container,
        _chamar_funcao(
            [1, 2],
            atualizacoes=(
                '{"descricao":"Conta quitada","categoria":"Moradia",'
                '"forma_pagamento":"PIX","vencimento":12,'
                '"data_transacao":"2026-10-02"}'
            ),
        ),
    )
    assert "2" in resultado.stdout.strip().splitlines()

    estado = _psql(
        postgres_container,
        "SELECT status || '|' || data_liquidacao::text || '|' || mes || '|' || ano::text "
        "|| '|' || descricao || '|' || categoria || '|' || forma_pagamento "
        "|| '|' || vencimento::text || '|' || data_transacao::text "
        "FROM public.transacoes ORDER BY id;",
    ).stdout.strip().splitlines()
    assert estado == [
        "Pago|2026-11-14|OUTUBRO|2026|Conta quitada|Moradia|PIX|12|2026-10-02",
        "Pago|2026-11-14|NOVEMBRO|2026|Conta quitada|Moradia|PIX|12|2026-10-02",
    ]


def test_postgres_liquida_registro_individual(postgres_container):
    _semear(postgres_container, [(3, "Pendente", None, 25.0, "NOVEMBRO", 2026)])
    resultado = _psql(postgres_container, _chamar_funcao([3]))
    assert "1" in resultado.stdout.strip().splitlines()


def test_postgres_rejeita_ids_duplicados_ausentes_e_estados_invalidos(postgres_container):
    _semear(postgres_container, [
        (4, "Pendente", None, 10.0, "NOVEMBRO", 2026),
        (5, "Pago", "2026-11-10", 20.0, "NOVEMBRO", 2026),
        (6, "Pendente", "2026-11-10", 30.0, "NOVEMBRO", 2026),
        (7, "Pendente", None, None, "NOVEMBRO", 2026),
    ])

    chamadas_invalidas = [
        _chamar_funcao([4, 4]),
        _chamar_funcao([4, 999]),
        _chamar_funcao([5]),
        _chamar_funcao([6]),
        _chamar_funcao([7]),
        _chamar_funcao([4], atualizacoes='{"valor":999}'),
        _chamar_funcao([4], atualizacoes='{"mes":"DEZEMBRO"}'),
        _chamar_funcao([4], atualizacoes='{"campo_inventado":true}'),
    ]
    for chamada in chamadas_invalidas:
        resultado = _psql(postgres_container, chamada, check=False)
        assert resultado.returncode != 0

    estado = _psql(
        postgres_container,
        "SELECT id || '|' || status || '|' || COALESCE(data_liquidacao::text, 'NULL') "
        "FROM public.transacoes ORDER BY id;",
    ).stdout.strip().splitlines()
    assert estado == [
        "4|Pendente|NULL",
        "5|Pago|2026-11-10",
        "6|Pendente|2026-11-10",
        "7|Pendente|NULL",
    ]


def test_postgres_rollback_integral_quando_trigger_falha_no_update(postgres_container):
    dollar = chr(36)
    _semear(postgres_container, [
        (8, "Pendente", None, 80.0, "NOVEMBRO", 2026),
        (9, "Pendente", None, 90.0, "NOVEMBRO", 2026),
    ])
    _psql(
        postgres_container,
        f"""
        CREATE OR REPLACE FUNCTION public.falha_controlada_liquidacao()
        RETURNS trigger LANGUAGE plpgsql AS {dollar}trigger{dollar}
        BEGIN
            IF NEW.id = 9 THEN
                RAISE EXCEPTION 'falha de teste durante UPDATE';
            END IF;
            RETURN NEW;
        END;
        {dollar}trigger{dollar};
        CREATE TRIGGER falha_controlada_liquidacao
        BEFORE UPDATE ON public.transacoes
        FOR EACH ROW EXECUTE FUNCTION public.falha_controlada_liquidacao();
        """,
    )

    resultado = _psql(postgres_container, _chamar_funcao([8, 9]), check=False)
    assert resultado.returncode != 0
    _psql(
        postgres_container,
        "DROP TRIGGER falha_controlada_liquidacao ON public.transacoes; "
        "DROP FUNCTION public.falha_controlada_liquidacao();",
    )
    estado = _psql(
        postgres_container,
        "SELECT status || '|' || COALESCE(data_liquidacao::text, 'NULL') "
        "FROM public.transacoes ORDER BY id;",
    ).stdout.strip().splitlines()
    assert estado == ["Pendente|NULL", "Pendente|NULL"]


def test_postgres_concorrencia_impede_dupla_liquidacao_do_mesmo_lote(postgres_container):
    dollar = chr(36)
    _semear(postgres_container, [
        (10, "Pendente", None, 100.0, "NOVEMBRO", 2026),
        (11, "Pendente", None, 110.0, "NOVEMBRO", 2026),
    ])
    _psql(
        postgres_container,
        f"""
        CREATE OR REPLACE FUNCTION public.atrasar_primeira_liquidacao()
        RETURNS trigger LANGUAGE plpgsql AS {dollar}trigger{dollar}
        BEGIN
            IF NEW.id = 10 THEN
                PERFORM pg_catalog.pg_sleep(1.5);
            END IF;
            RETURN NEW;
        END;
        {dollar}trigger{dollar};
        CREATE TRIGGER atrasar_primeira_liquidacao
        BEFORE UPDATE ON public.transacoes
        FOR EACH ROW EXECUTE FUNCTION public.atrasar_primeira_liquidacao();
        """,
    )

    comando = [
        "docker", "exec", postgres_container, "psql", "-X", "-v",
        "ON_ERROR_STOP=1", "-U", "postgres", "-d", "financeiro_pro_test",
        "-A", "-t", "-c", _chamar_funcao([10, 11]),
    ]
    primeira = subprocess.Popen(comando, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    comando_invertido = [
        *comando[:-1],
        _chamar_funcao([11, 10]),
    ]
    time.sleep(0.25)
    segunda = subprocess.Popen(
        comando_invertido,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    primeira_saida = primeira.communicate(timeout=10)
    segunda_saida = segunda.communicate(timeout=10)
    codigos = sorted([primeira.returncode, segunda.returncode])
    assert codigos == [0, 1], (primeira_saida, segunda_saida)

    estado = _psql(
        postgres_container,
        "SELECT status || '|' || data_liquidacao::text "
        "FROM public.transacoes ORDER BY id;",
    ).stdout.strip().splitlines()
    assert estado == ["Pago|2026-11-14", "Pago|2026-11-14"]


def test_postgres_rpc_nao_e_executavel_por_anon_ou_authenticated(postgres_container):
    resultado = _psql(
        postgres_container,
        "SELECT pg_catalog.has_function_privilege('anon', "
        "'public.liquidar_transacoes(bigint[],date,jsonb)', 'EXECUTE') || '|' || "
        "pg_catalog.has_function_privilege('authenticated', "
        "'public.liquidar_transacoes(bigint[],date,jsonb)', 'EXECUTE') || '|' || "
        "pg_catalog.has_function_privilege('service_role', "
        "'public.liquidar_transacoes(bigint[],date,jsonb)', 'EXECUTE');",
    )
    assert resultado.stdout.strip() == "false|false|true"
